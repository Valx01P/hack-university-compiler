-- The first migration: one small table to explore with psql, or to map with JPA.
-- Flyway runs every V<n>__<name>.sql in this folder once, in version order, when the app starts.
CREATE TABLE notes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body       text        NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now()
);
