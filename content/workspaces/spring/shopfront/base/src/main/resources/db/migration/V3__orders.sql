-- Orders and their lines. An order copies the currency, tax rate, and each unit price at the
-- moment it is placed, so later catalog or settings changes never rewrite history.
CREATE TABLE orders (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id           bigint      NOT NULL REFERENCES customers (id),
    status                text        NOT NULL CHECK (status IN ('PLACED', 'PAID', 'SHIPPED', 'CANCELLED')),
    currency              text        NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    tax_rate_basis_points integer     NOT NULL CHECK (tax_rate_basis_points BETWEEN 0 AND 10000),
    subtotal_cents        bigint      NOT NULL CHECK (subtotal_cents >= 0),
    tax_cents             bigint      NOT NULL CHECK (tax_cents >= 0),
    total_cents           bigint      NOT NULL,
    placed_at             timestamptz NOT NULL,
    cancelled_at          timestamptz,
    CHECK (total_cents = subtotal_cents + tax_cents),
    CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);

CREATE TABLE order_lines (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         bigint  NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id       bigint  NOT NULL REFERENCES products (id),
    quantity         integer NOT NULL CHECK (quantity > 0),
    unit_price_cents bigint  NOT NULL CHECK (unit_price_cents > 0),
    UNIQUE (order_id, product_id)
);
