-- The performance seed, for finding slow queries (lesson 41 and the taskboard-slow-list
-- challenge): project 100, "Load Test", owned by Ada with Grace and Linus as members,
-- holding 5,000 tasks (ids 1001 to 6000), 50,000 comments (10 per task, ids 100001 to
-- 150000), and one watcher per task. Load it after db/seed.sql:
--
--   go run ./cmd/seed -file db/seed_perf.sql
--
-- Every value is computed from its row number by generate_series, so every load makes
-- exactly the same rows, and ON CONFLICT DO NOTHING makes a second load change nothing.

BEGIN;

INSERT INTO projects (id, owner_id, name, description, color, created_at) OVERRIDING SYSTEM VALUE
VALUES (100, 1, 'Load Test', 'Generated by db/seed_perf.sql: 5,000 tasks and 50,000 comments.', '#0891b2', '2026-09-05T09:00:00Z')
ON CONFLICT DO NOTHING;

INSERT INTO project_members (project_id, user_id, role, created_at) VALUES
    (100, 1, 'owner', '2026-09-05T09:00:00Z'),
    (100, 2, 'member', '2026-09-05T09:00:00Z'),
    (100, 3, 'member', '2026-09-05T09:00:00Z')
ON CONFLICT DO NOTHING;

-- Task n is todo, doing, or done by n % 3, has priority n % 3 + 1, is due on one of
-- 120 days from 2026-09-01, and is assigned to nobody, Ada, Grace, or Linus by n % 4.
-- Done tasks get a completed_at, which tasks_completed_at_check requires.
INSERT INTO tasks (id, project_id, title, description, status, priority, due_on, assignee_id,
                   version, completed_at, created_at, updated_at) OVERRIDING SYSTEM VALUE
SELECT 1000 + n,
       100,
       'Load test task ' || n,
       CASE WHEN n % 5 = 0 THEN NULL ELSE 'Generated task number ' || n || '.' END,
       (ARRAY['todo', 'doing', 'done'])[n % 3 + 1],
       n % 3 + 1,
       DATE '2026-09-01' + n % 120,
       (ARRAY[NULL, 1, 2, 3]::bigint[])[n % 4 + 1],
       1,
       CASE WHEN n % 3 = 2 THEN TIMESTAMPTZ '2026-09-20 09:00:00Z' + make_interval(mins => n) END,
       TIMESTAMPTZ '2026-09-05 09:00:00Z' + make_interval(mins => n),
       TIMESTAMPTZ '2026-09-05 09:00:00Z' + make_interval(mins => n)
FROM generate_series(1, 5000) AS n
ON CONFLICT DO NOTHING;

-- Comment n belongs to task 1000 + ceil(n / 10), so each task has 10, a second apart.
INSERT INTO comments (id, task_id, author_id, body, created_at) OVERRIDING SYSTEM VALUE
SELECT 100000 + n,
       1000 + (n - 1) / 10 + 1,
       n % 3 + 1,
       'Generated comment ' || n || '.',
       TIMESTAMPTZ '2026-09-06 09:00:00Z' + make_interval(secs => n)
FROM generate_series(1, 50000) AS n
ON CONFLICT DO NOTHING;

INSERT INTO task_watchers (task_id, user_id, created_at)
SELECT 1000 + n, n % 3 + 1, TIMESTAMPTZ '2026-09-07 09:00:00Z'
FROM generate_series(1, 5000) AS n
ON CONFLICT DO NOTHING;

SELECT setval(pg_get_serial_sequence('projects', 'id'), (SELECT max(id) FROM projects));
SELECT setval(pg_get_serial_sequence('tasks', 'id'), (SELECT max(id) FROM tasks));
SELECT setval(pg_get_serial_sequence('comments', 'id'), (SELECT max(id) FROM comments));

-- Fresh statistics, so the planner knows the tables are big before the first EXPLAIN.
ANALYZE projects, project_members, tasks, comments, task_watchers;

COMMIT;
