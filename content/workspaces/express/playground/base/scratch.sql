  ('Riverside Brass', 'Denver', '2026-10-24T03:00:00Z', 3000),
  ('Synth Collective', 'Chicago', '2026-11-14T02:00:00Z', 2000),
  ('Folk at Dawn', 'Austin', '2026-11-21T01:00:00Z', 1800);

SELECT city, count(*) AS gigs, min(price_cents) AS cheapest_cents
FROM gigs
GROUP BY city
ORDER BY city;
